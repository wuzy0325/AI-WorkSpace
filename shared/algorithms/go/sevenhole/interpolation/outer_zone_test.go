// TestOuterZoneSectorFallback exercises the Python first/second candidate
// logic at the pipeline level: (ka,kb) computed for sector 2's map must miss
// sector 1's polygon (far shifted) and hit sector 2's.
func TestOuterZoneSectorFallback(t *testing.T) {
	farMap := func(theta, phi float64) (ka, kb, cpt, cps float64) {
		ka, kb, cpt, cps = linearOuterMap(0)(theta, phi)
		return ka + 100, kb + 100, cpt, cps // shift sector-1 cells far away
	}
	p := NewSevenHolePrbInterpolator()
	for sector, f := range map[int]func(float64, float64) (float64, float64, float64, float64){
		1: farMap,
		2: linearOuterMap(60),
	} {
		center := float64(sector-1) * 60
		lines := []string{"ka kb cpt cps a b"}
		for k := 0; k < outerPhiCount; k++ {
			b := normalize360(center + 30 - gridStep*float64(k))
			for it := 0; it < defaultTestThetaCount; it++ {
				theta := outerThetaMin + gridStep*float64(it)
				ka, kb, cpt, cps := f(theta, b)
				lines = append(lines, fmt.Sprintf("%s %s %s %s %.6f %.6f",
					strconv.FormatFloat(ka, 'g', -1, 64),
					strconv.FormatFloat(kb, 'g', -1, 64),
					strconv.FormatFloat(cpt, 'g', -1, 64),
					strconv.FormatFloat(cps, 'g', -1, 64),
					theta, b))
			}
		}
		if err := p.LoadOuterPrbLines(sector, lines, fmt.Sprintf("synthetic-%d.prb", sector)); err != nil {
			t.Fatalf("load sector %d: %v", sector, err)
		}
	}
	// Point from sector-2's map at (theta=38, phi=66).
	ka, kb, _, _ := linearOuterMap(60)(38, 66)
	if _, hit, err := p.outerZoneTrySector(1, ka, kb); err != nil || hit {
		t.Errorf("first candidate: hit=%v err=%v, want miss", hit, err)
	}
	got, hit, err := p.outerZoneTrySector(2, ka, kb)
	if err != nil || !hit {
		t.Fatalf("second candidate: hit=%v err=%v, want hit", hit, err)
	}
	if math.Abs(got.a-38) > 1e-9 || math.Abs(got.b-66) > 1e-9 {
		t.Errorf("inversion = (%v,%v), want (38,66)", got.a, got.b)
	}
}

// TestOuterCellLocation pins the big_cptcps_square cell branches (SKILL.md
// section 3.5), including the a=thetaMax and phi 355->0 wrap special cases.
// thetaCount=4 时 thetaMax=45；动态化后 outerThetaCellLo 接收 thetaCount 参数。
func TestOuterCellLocation(t *testing.T) {
	const thetaCount = 4
	thetaCases := []struct{ v, want float64 }{
		{30, 30}, {37.5, 35}, {44.999, 40}, {45, 40},
	}
	for _, tc := range thetaCases {
		if got := outerThetaCellLo(tc.v, thetaCount); got != tc.want {
			t.Errorf("outerThetaCellLo(%v, %d) = %v, want %v", tc.v, thetaCount, got, tc.want)
		}
	}
	// 动态：thetaCount=7 时 thetaMax=60，a=60 应收缩到 [55,60]
	t.Run("thetaCount=7 dynamic", func(t *testing.T) {
		const tc7 = 7
		cases := []struct{ v, want float64 }{
			{30, 30}, {55, 55}, {59.999, 55}, {60, 55}, // a=60 (thetaMax) → cell [55,60]
		}
		for _, tc := range cases {
			if got := outerThetaCellLo(tc.v, tc7); got != tc.want {
				t.Errorf("outerThetaCellLo(%v, %d) = %v, want %v", tc.v, tc7, got, tc.want)
			}
		}
	})
	phiCases := []struct {
		v      float64
		lo, hi float64
	}{
		{347.7, 345, 350},
		{354.999, 350, 355},
		{355, 355, 0},   // l==71 wrap branch
		{357.5, 355, 0}, // l==71 wrap branch
		{-2.5, 0, 5},    // negative b truncation (sector-1 wrap square)
		{0, 0, 5},
	}
	for _, tc := range phiCases {
		lo, hi := outerPhiCell(tc.v)
		if lo != tc.lo || hi != tc.hi {
			t.Errorf("outerPhiCell(%v) = (%v,%v), want (%v,%v)", tc.v, lo, hi, tc.lo, tc.hi)
		}
	}
}

// TestCoordTransform checks the (theta,phi)->(alpha,beta) transform against
// hand-computed values (SKILL.md section 3.7), including the load-bearing
// minus sign and the degenerate branch.
func TestCoordTransform(t *testing.T) {
	tests := []struct {
		theta, phi  float64
		alpha, beta float64
	}{
		{30, 0, 0, 30},   // phi=0: pure beta
		{30, 90, -30, 0}, // phi=90: pure -alpha
		{45, 90, -45, 0},
		{30, 270, 30, 0}, // phi=270: positive alpha (minus sign!)
		{45, 270, 45, 0},
		{30, 180, 0, -30}, // phi=180: negative beta
		{45, 45, -math.Atan(math.Tan(math.Pi/4)*math.Sin(math.Pi/4)) * 180 / math.Pi,
			math.Atan(math.Tan(math.Pi/4)*math.Cos(math.Pi/4)) * 180 / math.Pi},
		{89.5, 123, -89.5, 123}, // degenerate branch
		{90, 45, -90, 45},       // degenerate branch
	}
	for _, tc := range tests {
		alpha, beta := convertThetaPhiToAlphaBeta(tc.theta, tc.phi)
		if math.Abs(alpha-tc.alpha) > 1e-12 || math.Abs(beta-tc.beta) > 1e-12 {
			t.Errorf("convertThetaPhiToAlphaBeta(%v,%v) = (%v,%v), want (%v,%v)",
				tc.theta, tc.phi, alpha, beta, tc.alpha, tc.beta)
		}
	}
}

// TestOuterGeometryCounts checks polygon vertex counts and the quad-cell
// construction per sector. thetaCount=4 时 polygon=30 顶点（4+13+4+13 去重）、
// quad=36（3×12）；动态化后 quad 数量随 thetaCount 线性变化。
func TestOuterGeometryCounts(t *testing.T) {
	p := buildOuterTestInterpolator(t, 2, linearOuterMap(60))
	if got := len(p.outerPolygons[1]); got != 30 {
		t.Errorf("polygon vertex count = %d, want 30", got)
	}
	if got := len(p.outerQuads[1]); got != 36 {
		t.Errorf("quad count = %d, want 36", got)
	}
}

// TestOuterGeometryCounts_DynamicThetaCount 验证动态 thetaCount 下 quad 数量
// 随之变化：thetaCount=7 → quad=6×12=72；thetaCount=2 → quad=1×12=12。
func TestOuterGeometryCounts_DynamicThetaCount(t *testing.T) {
	for _, tc := range []struct {
		name       string
		thetaCount int
		wantQuads  int
	}{
		{"thetaCount=2 (minimum)", 2, 12},  // (2-1)×(13-1)=12
		{"thetaCount=4 (legacy)", 4, 36},   // (4-1)×12=36
		{"thetaCount=7 (extended)", 7, 72}, // (7-1)×12=72
		{"thetaCount=10 (wide)", 10, 108},  // (10-1)×12=108
	} {
		t.Run(tc.name, func(t *testing.T) {
			p := buildOuterTestInterpolatorTheta(t, 3, tc.thetaCount, linearOuterMap(120))
			if got := len(p.outerQuads[2]); got != tc.wantQuads {
				t.Errorf("quad count = %d, want %d", got, tc.wantQuads)
			}
		})
	}
}
