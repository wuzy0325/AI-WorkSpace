// linearOuterMap is a linear (theta, phiSigned) -> (ka,kb) map with sheared
// cells plus linear cpt/cps fields. phiSigned is the normalized phi mapped
// into the signed range around the sector center, so the map is continuous
// across the 0/360 wrap for sector 1. The kb slope sign matches the real
// calibration orientation: kb decreases as phi increases (Python big_cal_ab
// containment requires the phi-high edge to sit at the low-kb side).
func linearOuterMap(center float64) func(theta, phi float64) (ka, kb, cpt, cps float64) {
	return func(theta, phi float64) (ka, kb, cpt, cps float64) {
		s := phi - center
		if s > 180 {
			s -= 360
		} else if s < -180 {
			s += 360
		}
		ka = 0.03*theta + 0.01*s
		kb = -0.01*theta - 0.02*s
		cpt = 0.8 + 0.01*theta - 0.005*s
		cps = -0.3 + 0.004*theta + 0.002*s
		return ka, kb, cpt, cps
	}
}

// buildOuterTestInterpolator loads a synthetic outer sector grid generated by
// f via the real loader (geometry precompute included). thetaCount=4（默认）
// 以保持与历史黄金样本一致；如需其他维度请用 buildOuterTestInterpolatorTheta。
func buildOuterTestInterpolator(t *testing.T, sector int, f func(theta, phi float64) (ka, kb, cpt, cps float64)) *SevenHolePrbInterpolator {
	t.Helper()
	return buildOuterTestInterpolatorTheta(t, sector, defaultTestThetaCount, f)
}

// buildOuterTestInterpolatorTheta 用指定 thetaCount 构造合成外区网格。
func buildOuterTestInterpolatorTheta(t *testing.T, sector, thetaCount int, f func(theta, phi float64) (ka, kb, cpt, cps float64)) *SevenHolePrbInterpolator {
	t.Helper()
	center := float64(sector-1) * 60
	lines := []string{"ka kb cpt cps a b"}
	for k := 0; k < outerPhiCount; k++ {
		b := normalize360(center + 30 - gridStep*float64(k))
		for it := 0; it < thetaCount; it++ {
			theta := outerThetaMin + gridStep*float64(it)
			ka, kb, cpt, cps := f(theta, b)
			lines = append(lines, fmt.Sprintf("%s %s %s %s %.6f %.6f",
				strconv.FormatFloat(ka, 'g', -1, 64),
				strconv.FormatFloat(kb, 'g', -1, 64),
				strconv.FormatFloat(cpt, 'g', -1, 64),
				strconv.FormatFloat(cps, 'g', -1, 64),
				theta, b))
		}
	}
	p := NewSevenHolePrbInterpolator()
	if err := p.LoadOuterPrbLines(sector, lines, fmt.Sprintf("synthetic-%d.prb", sector)); err != nil {
		t.Fatalf("load synthetic outer grid: %v", err)
	}
	return p
}

// TestOuterZoneLinearMap checks the full outer pipeline (polygon test,
// (theta,phi) inversion, cpt/cps bilinear) over interior points of sector 3
// (no wrap) with a linear map: everything must be exact to float noise.
func TestOuterZoneLinearMap(t *testing.T) {
	const sector = 3
	f := linearOuterMap(120)
	p := buildOuterTestInterpolator(t, sector, f)
	points := []struct{ theta, phi float64 }{
		{37.5, 120}, {32.5, 91.3}, {44.9, 148.7}, {30.1, 119.9},
		{44.99, 90.01}, {40, 135.5},
	}
	for _, pt := range points {
		ka, kb, _, _ := f(pt.theta, pt.phi)
		got, hit, err := p.outerZoneTrySector(sector, ka, kb)
		if err != nil {
			t.Fatalf("(%v,%v): %v", pt.theta, pt.phi, err)
		}
		if !hit {
			t.Fatalf("(%v,%v): expected sector hit", pt.theta, pt.phi)
		}
		if math.Abs(got.a-pt.theta) > 1e-9 || math.Abs(got.b-pt.phi) > 1e-9 {
			t.Errorf("(%v,%v): inversion = (%v,%v)", pt.theta, pt.phi, got.a, got.b)
		}
		_, _, wantCpt, wantCps := f(pt.theta, pt.phi)
		if math.Abs(got.cpt-wantCpt) > 1e-9 || math.Abs(got.cps-wantCps) > 1e-9 {
			t.Errorf("(%v,%v): cpt/cps = (%v,%v), want (%v,%v)", pt.theta, pt.phi, got.cpt, got.cps, wantCpt, wantCps)
		}
	}
}

// TestOuterZoneSector1Wrap checks the wrap-around sector 1: a point with
// signed phi < 0 (stored phi > 330) must invert and interpolate exactly.
// The inverted b for the cell across the 0/360 boundary comes out negative
// (b1=0 minus offset), mirroring Python big_cal_ab.
func TestOuterZoneSector1Wrap(t *testing.T) {
	const sector = 1
	f := linearOuterMap(0)
	p := buildOuterTestInterpolator(t, sector, f)
	// phi=347.7 (signed -12.3): inside the (345,350) cell.
	ka, kb, _, _ := f(37.5, 347.7)
	got, hit, err := p.outerZoneTrySector(sector, ka, kb)
	if err != nil || !hit {
		t.Fatalf("wrap point: hit=%v err=%v", hit, err)
	}
	if math.Abs(got.a-37.5) > 1e-9 || math.Abs(got.b-347.7) > 1e-9 {
		t.Errorf("inversion = (%v,%v), want (37.5,347.7)", got.a, got.b)
	}
	_, _, wantCpt, wantCps := f(37.5, 347.7)
	if math.Abs(got.cpt-wantCpt) > 1e-9 || math.Abs(got.cps-wantCps) > 1e-9 {
		t.Errorf("cpt/cps = (%v,%v), want (%v,%v)", got.cpt, got.cps, wantCpt, wantCps)
	}

	// phi=357.5 (signed -2.5): inside the cell across 0/360; the inverted b
	// is negative (Python behavior) and the (0,5) cell extrapolates the
	// linear field exactly.
	ka, kb, _, _ = f(40, 357.5)
	got, hit, err = p.outerZoneTrySector(sector, ka, kb)
	if err != nil || !hit {
		t.Fatalf("cross-zero point: hit=%v err=%v", hit, err)
	}
	if math.Abs(got.a-40) > 1e-9 || math.Abs(got.b-(-2.5)) > 1e-9 {
		t.Errorf("inversion = (%v,%v), want (40,-2.5)", got.a, got.b)
	}
	_, _, wantCpt, wantCps = f(40, 357.5)
	if math.Abs(got.cpt-wantCpt) > 1e-9 || math.Abs(got.cps-wantCps) > 1e-9 {
		t.Errorf("cpt/cps = (%v,%v), want (%v,%v)", got.cpt, got.cps, wantCpt, wantCps)
	}
}

