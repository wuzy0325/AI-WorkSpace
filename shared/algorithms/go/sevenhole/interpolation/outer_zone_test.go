func TestMaxPressureHoles(t *testing.T) {
	tests := []struct {
		name          string
		p             [6]float64
		first, second int
	}{
		{"distinct", [6]float64{1, 5, 3, 2, 6, 4}, 5, 2},
		{"first hole max", [6]float64{9, 1, 2, 3, 4, 5}, 1, 6},
		{"last hole max", [6]float64{1, 2, 3, 4, 5, 9}, 6, 5},
		{"negative pressures", [6]float64{-5, -1, -9, -2, -3, -4}, 2, 4},
		// Tie at the top: Python picks the first key for both first and
		// second (sorted values equal), so first==second.
		{"tie at top", [6]float64{7, 7, 1, 2, 3, 4}, 1, 1},
		// Tie below the top: second is the first hole with the 2nd value.
		{"tie at second", [6]float64{9, 5, 5, 1, 2, 3}, 1, 2},
	}
	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			in := InterpolationInput{
				P1: tc.p[0], P2: tc.p[1], P3: tc.p[2],
				P4: tc.p[3], P5: tc.p[4], P6: tc.p[5],
			}
			first, second := maxPressureHoles(in)
			if first != tc.first || second != tc.second {
				t.Errorf("maxPressureHoles = (%d,%d), want (%d,%d)", first, second, tc.first, tc.second)
			}
		})
	}
}

func TestOuterKaKb(t *testing.T) {
	// Sector 1: pc=P1, pl=P6, pr=P2. pc=100, pl=pr=0, p7=20 ->
	// denom=100, ka=0.8, kb=0.
	in := InterpolationInput{P1: 100, P7: 20}
	ka, kb, err := outerKaKb(in, 1)
	if err != nil {
		t.Fatalf("outerKaKb: %v", err)
	}
	if math.Abs(ka-0.8) > 1e-15 || math.Abs(kb-0) > 1e-15 {
		t.Errorf("sector1 (ka,kb) = (%v,%v), want (0.8,0)", ka, kb)
	}

	// Sector 3: pc=P3=50, pl=P2=10, pr=P4=20, p7=5 ->
	// denom=35, ka=45/35=9/7, kb=-10/35=-2/7.
	in = InterpolationInput{P2: 10, P3: 50, P4: 20, P7: 5}
	ka, kb, err = outerKaKb(in, 3)
	if err != nil {
		t.Fatalf("outerKaKb: %v", err)
	}
	if math.Abs(ka-9.0/7.0) > 1e-15 || math.Abs(kb-(-2.0/7.0)) > 1e-15 {
		t.Errorf("sector3 (ka,kb) = (%v,%v), want (%v,%v)", ka, kb, 9.0/7.0, -2.0/7.0)
	}

	// Sector 6 wrap: pr=P1.
	in = InterpolationInput{P1: 8, P5: 2, P6: 40, P7: 4}
	ka, kb, err = outerKaKb(in, 6)
	if err != nil {
		t.Fatalf("outerKaKb: %v", err)
	}
	// denom = 40 - (2+8)/2 = 35; ka = (40-4)/35 = 36/35; kb = (2-8)/35 = -6/35.
	if math.Abs(ka-36.0/35.0) > 1e-15 || math.Abs(kb-(-6.0/35.0)) > 1e-15 {
		t.Errorf("sector6 (ka,kb) = (%v,%v), want (%v,%v)", ka, kb, 36.0/35.0, -6.0/35.0)
	}
}

