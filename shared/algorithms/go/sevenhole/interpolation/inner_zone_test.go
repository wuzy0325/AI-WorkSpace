// linearInnerMap is a strictly linear (a,b) -> (ka,kb) map with sheared
// cells, plus linear cpt/cps fields. Under a linear map every cell is a
// parallelogram, so the edge-equation inversion is exact, and the bilinear
// stage reproduces linear fields exactly.
func linearInnerMap(a, b float64) (ka, kb, cpt, cps float64) {
	ka = 0.05*a + 0.01*b
	kb = -0.02*a + 0.04*b
	cpt = 1.1 + 0.03*a - 0.02*b
	cps = -0.5 - 0.01*a + 0.04*b
	return ka, kb, cpt, cps
}

// buildInnerTestInterpolator loads a synthetic inner grid whose ka/kb/cpt/cps
// are generated by f, via the real loader (geometry precompute included).
// Coefficients are written with shortest round-trip formatting so the stored
// grid values are bit-identical to evaluating f at the grid coordinates.
func buildInnerTestInterpolator(t *testing.T, f func(a, b float64) (ka, kb, cpt, cps float64)) *SevenHolePrbInterpolator {
	t.Helper()
	lines := []string{"ka kb cpt cps a b"}
	for ia := 0; ia < innerGridSide; ia++ {
		for ib := 0; ib < innerGridSide; ib++ {
			a := innerGridMin + gridStep*float64(ia)
			b := innerGridMin + gridStep*float64(ib)
			ka, kb, cpt, cps := f(a, b)
			lines = append(lines, fmt.Sprintf("%s %s %s %s %.6f %.6f",
				strconv.FormatFloat(ka, 'g', -1, 64),
				strconv.FormatFloat(kb, 'g', -1, 64),
				strconv.FormatFloat(cpt, 'g', -1, 64),
				strconv.FormatFloat(cps, 'g', -1, 64),
				a, b))
		}
	}
	p := NewSevenHolePrbInterpolator()
	if err := p.LoadInnerPrbLines(lines, "synthetic-7.prb"); err != nil {
		t.Fatalf("load synthetic inner grid: %v", err)
	}
	return p
}

// TestInnerZoneLinearMap checks stage A (a,b inversion) and stage B (cpt/cps
// bilinear) over interior and near-boundary points of a linear map:
// inversion must be exact to float noise. Points strictly inside the grid
// are used: exact max-edge grid-line hits are float-fragile in the
// edge-equation location in BOTH implementations (identical formulas), so
// boundary routing is pinned separately by TestInnerZoneBoundaryRouting.
func TestInnerZoneLinearMap(t *testing.T) {
	p := buildInnerTestInterpolator(t, linearInnerMap)
	points := []struct{ a, b float64 }{
		{0, 0}, {12.3, -7.8}, {-22.9, 17.6}, {29.9, -29.9},
		{29.9999, 0}, {15, 29.9999}, {29.9999, 29.9999},
	}
	for _, pt := range points {
		ka, kb, _, _ := linearInnerMap(pt.a, pt.b)
		got, inZone, err := p.innerZoneInterpolate(ka, kb)
		if err != nil {
			t.Fatalf("(%v,%v): %v", pt.a, pt.b, err)
		}
		if !inZone {
			t.Fatalf("(%v,%v): expected inner zone", pt.a, pt.b)
		}
		if math.Abs(got.a-pt.a) > 1e-9 || math.Abs(got.b-pt.b) > 1e-9 {
			t.Errorf("(%v,%v): inversion = (%v,%v)", pt.a, pt.b, got.a, got.b)
		}
		_, _, wantCpt, wantCps := linearInnerMap(pt.a, pt.b)
		if math.Abs(got.cpt-wantCpt) > 1e-9 || math.Abs(got.cps-wantCps) > 1e-9 {
			t.Errorf("(%v,%v): cpt/cps = (%v,%v), want (%v,%v)", pt.a, pt.b, got.cpt, got.cps, wantCpt, wantCps)
		}
	}
}

// TestInnerZoneOutside checks the not-inner signal (no error) for a point far
// outside the boundary polygon (Python cal_ab falls through to big angle).
func TestInnerZoneOutside(t *testing.T) {
	p := buildInnerTestInterpolator(t, linearInnerMap)
	if _, inZone, err := p.innerZoneInterpolate(100, 100); err != nil || inZone {
		t.Errorf("outside point: inZone=%v err=%v, want false,nil", inZone, err)
	}
}

