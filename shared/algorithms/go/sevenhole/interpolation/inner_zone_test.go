func TestInnerKaKb(t *testing.T) {
	// p1..p6 = {0,0,0,50,25,75} -> pAvg=25; p7=125 -> denom=100.
	// cpa=0.5, cpb=0.25, cpc=0.75; ka=1/sqrt(3), kb=-0.5/3.
	in := InterpolationInput{P1: 0, P2: 0, P3: 0, P4: 50, P5: 25, P6: 75, P7: 125}
	ka, kb, err := innerKaKb(in)
	if err != nil {
		t.Fatalf("innerKaKb: %v", err)
	}
	if want := 1 / math.Sqrt(3); math.Abs(ka-want) > 1e-15 {
		t.Errorf("ka = %v, want %v", ka, want)
	}
	if want := -0.5 / 3; math.Abs(kb-want) > 1e-15 {
		t.Errorf("kb = %v, want %v", kb, want)
	}
}

