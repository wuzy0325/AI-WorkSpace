export const useI18nStore = defineStore('i18n', () => {
  const saved = (typeof localStorage !== 'undefined' && localStorage.getItem('wind-daq.locale')) as Locale | null
  const locale = ref<Locale>(saved ?? 'zh')

  function setLocale(newLocale: Locale) {
    locale.value = newLocale
    try {
      localStorage.setItem('wind-daq.locale', newLocale)
    } catch {
      // localStorage not available
    }
  }

  const t = computed(() => (locale.value === 'zh' ? zh : en))

  return { locale, setLocale, t }
})
