// channelColors.ts 为 18 通道波形提供统一的默认调色板与颜色解析逻辑。
// p1604 共 18 通道：CH01~CH16 压力通道、CH17 大气压力、CH18 大气温度。
//
// 设计原则：
// - 默认色板作为唯一事实来源（defaultChannels / 波形图 / 通道卡片共用），
//   避免 deviceStore 与图表各自维护一套色板导致"存色"与"取色"不一致。
// - 前 16 色按「色相 × 明度」两维生成，保证细线在白底下两两可区分：
//   16 个色相从 100° 起以 17° 步进均匀铺满色轮（避开 25°~95° 黄/橙/琥珀警戒色区，
//   防止与警告状态混淆），并循环搭配 亮/中/深 三档明度与饱和度；
//   再按交错顺序（0,8,1,9,…）分配到通道，使相邻通道色相错开约半轮。
//   两两 RGB 距离 ≥ 54，相邻通道 ≥ 160，远好于旧色板中多款青/蓝近色并存的情况。
// - CH17 大气压力 / CH18 大气温度用中性灰（冷灰/暖灰），与压力通道的彩色区分。
//
// 颜色解析统一走 channelColor()：
// - 已保存的自定义颜色优先；
// - 未设置时按通道物理索引（而非选中/启用顺序）回退到默认色板，
//   保证同一通道在任何通道组合下颜色恒定，卡片圆点与波形颜色一致。

