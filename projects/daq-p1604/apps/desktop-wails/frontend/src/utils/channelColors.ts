// channelColors.ts 为 18 通道波形提供统一的默认调色板与颜色解析逻辑。
// p1604 共 18 通道：CH01~CH16 压力通道、CH17 大气压力、CH18 大气温度。
//
// 设计原则：
// - 默认色板作为唯一事实来源（defaultChannels / 波形图 / 通道卡片共用），
//   避免 deviceStore 与图表各自维护一套色板导致"存色"与"取色"不一致。
// - 剔除易与「警告/异常」状态混淆的琥珀/橙/黄（amber/orange/yellow）。
// - 前 16 色为压力通道：10 种高饱和基色 + 6 种同色系深色变体，相邻通道色相不同，
//   避免旧色板中三款橙黄近色并存导致细线难以区分的问题。
// - CH17 大气压力 / CH18 大气温度用中性灰（冷灰/暖灰），与压力通道的彩色区分。
//
// 颜色解析统一走 channelColor()：
// - 已保存的自定义颜色优先；
// - 未设置时按通道物理索引（而非选中/启用顺序）回退到默认色板，
//   保证同一通道在任何通道组合下颜色恒定，卡片圆点与波形颜色一致。

/** 18 通道默认波形配色 */
export const CHANNEL_COLORS = [
  '#3b82f6', '#22c55e', '#a855f7', '#ef4444',
  '#06b6d4', '#ec4899', '#84cc16', '#6366f1',
  '#14b8a6', '#d946ef', '#2563eb', '#16a34a',
  '#9333ea', '#dc2626', '#0891b2', '#db2777',
  '#64748b', '#78716c',
]

/**
 * 旧版本默认色板（含琥珀/橙/黄近色），仅用于迁移：
 * 将「颜色 == 旧色板中该索引的默认色」的通道视为未自定义，
 * 迁移为空串后回退到新的统一色板，使用户已有的默认配置也能自动换上新配色。
 */
export const LEGACY_CHANNEL_COLORS = [
  '#3b82f6', '#10b981', '#f59e0b', '#a855f7',
  '#f43f5e', '#06b6d4', '#f97316', '#6366f1',
  '#84cc16', '#14b8a6', '#d946ef', '#0ea5e9',
  '#eab308', '#22c55e', '#ef4444', '#8b5cf6',
  '#64748b', '#78716c',
]

/** 解析通道波形颜色：自定义颜色优先，否则按通道索引回退默认色板 */
export function channelColor(storedColor: string, channelIndex: number): string {
  return storedColor || CHANNEL_COLORS[channelIndex % CHANNEL_COLORS.length]
}
