// 网格参数
const GRID_ALPHA_VALUES: readonly number[] = [-30, -25, -20, -15, -10, -5, 0, 5, 10, 15, 20, 25, 30]
const GRID_BETA_VALUES: readonly number[] = [-30, -25, -20, -15, -10, -5, 0, 5, 10, 15, 20, 25, 30]
const GRID_SIZE = 13

/** 根据网格索引获取原始数据 */
function getRawEntry(alphaIdx: number, betaIdx: number): LookupEntry {
  return RAW_DATA[betaIdx * GRID_SIZE + alphaIdx]
}

// ── 双线性插值 ──────────────────────────────────────────────────

function findGridIndex(value: number, gridValues: readonly number[]): { lo: number; hi: number; frac: number } {
  if (value <= gridValues[0]) return { lo: 0, hi: 0, frac: 0 }
  if (value >= gridValues[gridValues.length - 1]) return { lo: gridValues.length - 1, hi: gridValues.length - 1, frac: 0 }

  for (let i = 0; i < gridValues.length - 1; i++) {
    if (value >= gridValues[i] && value <= gridValues[i + 1]) {
      const range = gridValues[i + 1] - gridValues[i]
      const frac = range === 0 ? 0 : (value - gridValues[i]) / range
      return { lo: i, hi: i + 1, frac }
    }
  }

  return { lo: 0, hi: 0, frac: 0 }
}

/** 双线性插值查找：根据(α, β)查表，支持非网格点 */
function interpolateEntry(alpha: number, beta: number, jitter: boolean): { rawData: FiveHoleRawData; coefficients: FiveHoleCoefficients } {
  const ax = findGridIndex(alpha, GRID_ALPHA_VALUES)
  const bx = findGridIndex(beta, GRID_BETA_VALUES)

  // 四个角点的数据
  const e00 = getRawEntry(ax.lo, bx.lo)
  const e10 = getRawEntry(ax.hi, bx.lo)
  const e01 = getRawEntry(ax.lo, bx.hi)
  const e11 = getRawEntry(ax.hi, bx.hi)

  const fa = ax.frac
  const fb = bx.frac

  const n = () => jitter ? gaussianNoise() : 0
  const jitterFactor = () => 1 + n() * 0.015

  // 双线性插值每个通道
  const interp = (col: number) => {
    const top = e00[col] * (1 - fa) + e10[col] * fa
    const bot = e01[col] * (1 - fa) + e11[col] * fa
    return (top * (1 - fb) + bot * fb)
  }

  // 系数也用插值结果（来自 CSV 预计算），但噪声会按比例扰动系数（与原始压力噪声同量级）
  const coeffJitter = () => 1 + n() * 0.015

  const rawData: FiveHoleRawData = {
    p1: interp(0) * (jitter ? jitterFactor() : 1),
    p2: interp(1) * (jitter ? jitterFactor() : 1),
    p3: interp(2) * (jitter ? jitterFactor() : 1),
    p4: interp(3) * (jitter ? jitterFactor() : 1),
    p5: interp(4) * (jitter ? jitterFactor() : 1),
    pAtm: interp(5) + n() * 5,
    tAtm: interp(6) + n() * 0.05,
    pTotal: interp(7),
    pStatic: interp(8),
  }

  const coefficients: FiveHoleCoefficients = {
    Kalpha: interp(10) * (jitter ? coeffJitter() : 1),
    Kbeta: interp(11) * (jitter ? coeffJitter() : 1),
    CPT: interp(12) * (jitter ? coeffJitter() : 1),
    CPS: interp(13) * (jitter ? coeffJitter() : 1),
    machNumber: interp(9),
  }

  return { rawData, coefficients }
}

// ── 简单高斯噪声（Box-Muller） ─────────────────────────────────

function gaussianNoise(): number {
  let u = 0, v = 0
  while (u === 0) u = Math.random()
  while (v === 0) v = Math.random()
  return Math.sqrt(-2.0 * Math.log(u)) * Math.cos(2.0 * Math.PI * v)
}

// ── 公开API ─────────────────────────────────────────────────────

export interface SimulationConfig {
  /** 点位布局 */
  layout: FiveHolePointLayout
  /** 是否添加随机噪声 */
  noise: boolean
  /** 显式点位顺序；传入时优先于 layout */
  points?: CalibrationPoint[]
}

/**
 * 为指定的 (α, β) 生成一个模拟校准数据点
 */
export function generateSimulatedPoint(
  alpha: number,
  beta: number,
  pointId: number,
  noise: boolean = true
): CalibrationDataPoint {
  const { rawData, coefficients } = interpolateEntry(alpha, beta, noise)

  return {
    pointId,
    coordinates: { α: alpha, β: beta },
    rawData,
    coefficients,
    sampleCount: 10,
    stdDev: noise ? Math.random() * 1.5 : 0,
    startTime: Date.now() - 1200,
    endTime: Date.now(),
  }
}

/**
 * 根据显式点位顺序或布局配置批量生成模拟校准数据点
 * 未传 points 时，默认严格按 CSV 原始行序生成：
 * β 从 -30 到 30，每行内 α 从 -30 到 30 递增。
 */
export function generateSimulatedPoints(config: SimulationConfig): CalibrationDataPoint[] {
  const { layout, noise, points } = config
  if (points && points.length > 0) {
    return points.map((point, index) => generateSimulatedPoint(
      point.coordinates['α'] ?? 0,
      point.coordinates['β'] ?? 0,
      point.id ?? index,
      noise
    ))
  }

  const alphaValues = buildRange(layout.alphaMin, layout.alphaMax, layout.alphaStep)
  const betaValues = buildRange(layout.betaMin, layout.betaMax, layout.betaStep)

  const generatedPoints: CalibrationDataPoint[] = []
  let id = 0

  // CSV 行序：每个 beta 固定一行，行内 alpha 单调递增
  betaValues.forEach((beta) => {
    const alphas = alphaValues
    alphas.forEach((alpha) => {
      generatedPoints.push(generateSimulatedPoint(alpha, beta, id++, noise))
    })
  })

  return generatedPoints
}

function buildRange(min: number, max: number, step: number): number[] {
  const values: number[] = []
  for (let value = min; value <= max + 1e-9; value += step) {
    values.push(Number(value.toFixed(10)))
  }
  return values
}

// ── 校准覆盖网格（无噪声） ─────────────────────────────────────

export interface GridCoefficient {
  /** α 方向网格索引 0..12 */
  alphaIdx: number
  /** β 方向网格索引 0..12 */
  betaIdx: number
  /** α 实际值（°） */
  alpha: number
  /** β 实际值（°） */
  beta: number
  /** Kα 系数（CSV 预计算，无噪声） */
  Kalpha: number
  /** Kβ 系数（CSV 预计算，无噪声） */
  Kbeta: number
}

/**
 * 返回 13×13 校准覆盖网格上所有 169 点的干净 Kα/Kβ 系数。
 *
 * 用途：Kα-Kβ 系数特征空间图（覆盖图 / 网格图），不论模拟走到哪一步都画完整 13×13 网格。
 *
 * 注意：RAW_DATA 内部按蛇形存储（偶数 β 行 α 升序、奇数 β 行 α 降序），
 * 但对外统一按 (alphaIdx, betaIdx) 顺序展开，不依赖存储布局。
 */
export function getAllGridCoefficients(): GridCoefficient[] {
  const points: GridCoefficient[] = []
  for (let betaIdx = 0; betaIdx < GRID_SIZE; betaIdx++) {
    for (let alphaIdx = 0; alphaIdx < GRID_SIZE; alphaIdx++) {
      const storageAlphaIdx = betaIdx % 2 === 0 ? alphaIdx : (GRID_SIZE - 1 - alphaIdx)
      const entry = RAW_DATA[betaIdx * GRID_SIZE + storageAlphaIdx]
      points.push({
        alphaIdx,
        betaIdx,
        alpha: GRID_ALPHA_VALUES[alphaIdx],
        beta: GRID_BETA_VALUES[betaIdx],
        Kalpha: entry[10],
        Kbeta: entry[11],
      })
    }
  }
  return points
}
